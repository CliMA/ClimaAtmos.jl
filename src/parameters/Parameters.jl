  - `beres_source_params`: `BeresSourceParameters`, or `nothing`.
  - `Omega`: Angular velocity of planetary rotation [rad/s].
  - `f_plane_coriolis_frequency`: Coriolis frequency on an f-plane [1/s].
  - `planet_radius`: Mean radius of the planet [m].
  - `astro_unit`: Astronomical unit [m].
