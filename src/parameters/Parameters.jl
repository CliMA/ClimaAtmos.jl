"""
    Parameters

Parameter structs for ClimaAtmos and accessors for their values.

The top-level container is `ClimaAtmosParameters`, which holds the
parameters that ClimaAtmos owns directly, together with the parameter sets of
the packages it calls (Thermodynamics, CloudMicrophysics, SurfaceFluxes, RRTMGP,
and Insolation). The structs here are plain, immutable, `isbits` value types, so
they can be captured by GPU kernels; they are built from a ClimaParams TOML
dictionary by the constructors in `create_parameters.jl`.

Every parameter is read through an accessor function of one argument, e.g.
`CAP.planet_radius(params)`, rather than by field access. The accessors are
generated by `@eval` loops at the bottom of this module, one loop per parameter
set, and they all take an `AbstractClimaAtmosParameters`. Three patterns appear:

  - Fields of `ClimaAtmosParameters` itself, forwarded as `ps.\$var`.
  - Fields of a sub-parameter set, forwarded through the accessor of that set,
    e.g. `max_area(ps) = max_area(turbconv_params(ps))`.
  - Parameters owned by another package, forwarded to that package's accessor,
    e.g. `R_d(ps) = TD.Parameters.R_d(thermodynamics_params(ps))`.

The uniform one-argument interface is what lets a tendency ask for a parameter
without knowing which package defines it, and lets parameter sets be swapped
(for calibration, or for a reduced set) without touching call sites.
"""
module Parameters

import ClimaCore as CC
import Insolation.Parameters as IP
import Thermodynamics as TD
import CloudMicrophysics as CM
import SurfaceFluxes as SF

"""
    AbstractClimaAtmosParameters

Supertype of the top-level ClimaAtmos parameter sets, aliased `ACAP`.

Every generated accessor dispatches on this type, so an alternative parameter
container only has to subtype it and provide the sub-parameter-set accessors.
The only concrete subtype is `ClimaAtmosParameters`.
"""
abstract type AbstractClimaAtmosParameters end
const ACAP = AbstractClimaAtmosParameters

"""
    AbstractTurbulenceConvectionParameters

Supertype of the turbulence-convection (PROPHET/EDMF) parameter sets, aliased
`ATCP`. The only concrete subtype is `TurbulenceConvectionParameters`.
"""
abstract type AbstractTurbulenceConvectionParameters end
const ATCP = AbstractTurbulenceConvectionParameters

"""
    AbstractSurfaceTemperatureParameters

Supertype of the prescribed-surface-temperature parameter sets, aliased `ASTP`.
The only concrete subtype is `SurfaceTemperatureParameters`.
"""
abstract type AbstractSurfaceTemperatureParameters end
const ASTP = AbstractSurfaceTemperatureParameters

"""
    AbstractGravityWaveParameters

Supertype of the gravity-wave parameter sets, aliased `AGWP`.

Subtypes:

  - `NonOrographicGravityWaveParameters`: Alexander-Dunkerton spectral
    source and propagation.
  - `OrographicGravityWaveParameters`: Garner topographic drag.
  - `BeresSourceParameters`: Beres convective source for the
    non-orographic scheme.
"""
abstract type AbstractGravityWaveParameters end
const AGWP = AbstractGravityWaveParameters

Base.broadcastable(param_set::ACAP) = tuple(param_set)
Base.broadcastable(param_set::ATCP) = tuple(param_set)
Base.broadcastable(param_set::ASTP) = tuple(param_set)

"""
    TurbulenceConvectionParameters{FT, VFT1, VFT2, VTF3} <: AbstractTurbulenceConvectionParameters

Parameters of the PROPHET (prognostic EDMF) turbulence and convection scheme.

Most values come from ClimaParams; see the `TurbulenceConvectionParameters`
constructor in `create_parameters.jl` for the mapping from ClimaParams names to
the fields below, and for the defaults of the few fields that ClimaParams does
not yet define. `FT` is the float type; `VFT1`, `VFT2`, and `VTF3` are the
`SVector` types of the three data-driven parameter vectors.

# Fields

  - `max_surface_area`: Maximum combined updraft area fraction at the surface,
    reached in the free-convection limit of the surface mass-flux closure [-].
  - `max_area`: Maximum area fraction per updraft [-].
  - `min_area`: Minimum area fraction per updraft [-].
  - `tke_ed_coeff`: TKE diffusivity coefficient `c_m` of the mixing-length
    closure [-].
  - `Ri_crit`: Critical gradient Richardson number [-].
  - `tke_surf_scale`: Ratio of surface-layer TKE to the squared friction
    velocity [-].
  - `tke_surf_flux_coeff`: Coefficient of the flux term in the `u*³` surface TKE
    flux [-].
  - `diagnostic_covariance_coeff`: Prefactor of the turbulent production term in
    the diagnostic covariance closure [-].
  - `sgs_variance_coeff_q`: Coefficient of an optional background SGS total-water
    variance source added to the diagnostic covariance, with standard deviation
    `σ_q = sgs_variance_coeff_q * q_tot` (grid-mean total water). Restores subgrid
    variance where the gradient*mixing-length closure collapses (free troposphere,
    at the mixing-length floor). `0` disables it (default); experimental [-].
  - `sgs_variance_coeff_T`: As `sgs_variance_coeff_q`, for the temperature
    variance, with `σ_T = sgs_variance_coeff_T * T`. `0` disables (default);
    experimental [-].
  - `sgs_variance_coeff_hgrad`: Coefficient of an optional horizontal-gradient
    (scale-similarity / mesoscale) SGS total-water variance source added to the
    diagnostic covariance. It adds a variance proportional to the resolved
    horizontal humidity gradient and the squared grid scale, and so survives
    where turbulence (and the mixing length) collapses in the free troposphere,
    self-targeting fronts and storm tracks. `0` disables it (default);
    experimental [-].
  - `sgs_variance_max_rel_std`: Upper bound on the SGS total-water standard
    deviation relative to the grid-mean total water, `σ_q ≤ sgs_variance_max_rel_std * q_tot`,
    applied when the horizontal-gradient source is active. The 3-point
    Gauss-Hermite quadrature samples `q̂ = q_tot ± √3 σ_q`, so a Gaussian wider than
    `q_tot/√3` puts a node at negative total water; the node is clamped to zero
    without re-weighting, which makes the sampled distribution carry more water
    than the grid mean and can drive the grid-mean vapour negative where the
    resolved horizontal gradient is large next to nearly dry air. `0.5` keeps all
    nodes non-negative (default); experimental [-].
  - `Tq_correlation_coefficient`: Default correlation between `T'` and `q_tot'`
    in the SGS quadrature, in `[-1, 1]` [-].
  - `static_stab_coeff`: Static stability coefficient `c_b` of the mixing-length
    closure [-].
  - `Prandtl_number_scale`: Cospectral budget factor `ω_pr` for the turbulent
    Prandtl number [-].
  - `Prandtl_number_0`: Turbulent Prandtl number in neutral conditions [-].
  - `Pr_max`: Maximum allowed turbulent Prandtl number [-].
  - `smin_ub`: Lower limit of the smooth-minimum function in the mixing-length
    closure [-].
  - `smin_rm`: Upper ratio limit of the smooth-minimum function in the
    mixing-length closure [-].
  - `min_updraft_top`: Minimum updraft height used by the entrainment limiter
    [m].
  - `pressure_normalmode_buoy_coeff1`: Buoyancy coefficient of the perturbation
    pressure closure [-].
  - `pressure_normalmode_drag_coeff`: Drag coefficient of the perturbation
    pressure closure [-].
  - `entr_inv_tau`: Inverse timescale of entrainment [1/s].
  - `entr_inv_length`: Coefficient of the `w` term in the entrainment closure,
    an inverse length scale [1/m].
  - `entr_coeff`: Coefficient of the `w/z` term in the entrainment closure [-].
  - `entr_buoy_coeff`: Coefficient of the `b/w²` term in the entrainment closure
    [-].
  - `entr_detr_buoy_inv_tau_max`: Cap on the inverse buoyancy timescale,
    limiting buoyancy-driven entrainment and detrainment when velocity
    differences become small [1/s].
  - `entr_detr_limit_inv_tau`: Inverse timescale of entrainment and detrainment
    at negligible area fraction [1/s].
  - `detr_inv_tau`: Inverse timescale of detrainment [1/s].
  - `detr_coeff`: Coefficient of the `w` term in the detrainment closure [-].
  - `detr_buoy_coeff`: Coefficient of the `b/w²` term in the detrainment closure
    [-].
  - `detr_vertdiv_coeff`: Coefficient of the vertical-divergence term in the
    detrainment closure [-].
  - `entr_param_vec`: Data-driven entrainment parameter vector [-].
  - `turb_entr_param_vec`: Data-driven turbulent-entrainment parameter vector
    [-].
  - `entr_mult_limiter_coeff`: Exponent of the multiplicative entrainment limiter
    `(1 - a)^c` [-].
  - `detr_massflux_vertdiv_coeff`: Coefficient of the mass-flux
    vertical-divergence term in the detrainment closure [-].
  - `min_area_limiter_scale`: Rate coefficient of the minimum-area limiter in
    entrainment [1/s].
  - `min_area_limiter_power`: Exponent of the minimum-area limiter [-].
  - `max_area_limiter_scale`: Rate coefficient of the maximum-area limiter in
    detrainment [1/s].
  - `max_area_limiter_power`: Exponent of the maximum-area limiter [-].
  - `cloud_fraction_steepness_scale`: Steepness scale `α` of the
    cloud-fraction/condensate relationship; 1 for exact Gaussian or lognormal SGS
    distributions [-].
  - `cloud_fraction_param_vec`: Data-driven cloud-fraction parameter vector [-].
  - `cloud_fraction_eps_rel`: Residual fractional saturation variability
    `ε_rel` in the augmented-`σ` floor of the cloud-fraction closure [-].
  - `cloud_fraction_sigma_abs`: Absolute floor `σ_abs` on the augmented
    saturation-deficit standard deviation [kg/kg].
  - `cloud_fraction_floor_release_margin`: Saturation margin `c_w`, in
    equilibrium PDF widths, at which the relative floor is released [-].
  - `cloud_fraction_floor_release_abs_margin`: Absolute margin `c_a`, in floor
    units, added in quadrature to the release width [-].
  - `cloud_fraction_floor_release_sharpness`: Exponent `s` of the release
    transition; larger values approach a switch [-].
  - `cloud_fraction_floor_residual`: Fraction `D_min` of the relative floor
    retained deep inside a saturated deck [-].
  - `sedimentation_lateral_coeff`: Scaling of the lateral correction in updraft
    sedimentation; 1 is the full correction and 0 disables it [-].
  - `interface_entr_efficiency`: Entrainment efficiency `A` in the interfacial
    entrainment diffusivity `K_e = γ w_e Δz` [-].
  - `sfc_mass_flux_ustar_coeff`: Coefficient `c_u` weighting the
    friction-velocity contribution in the surface mass-flux blend [-].
  - `convective_zi`: Prescribed convective boundary-layer depth `z_i` used in the
    surface mass-flux closure [m].
  - `sfc_mass_flux_cap_fraction`: Fraction `α` of the surface scalar flux that
    the updraft may transport, so the environment retains at least `1 - α` [-].
"""
Base.@kwdef struct TurbulenceConvectionParameters{FT, VFT1, VFT2, VTF3} <: ATCP
    max_surface_area::FT
