#####
##### Generated accessors
#####
##### Each loop below defines one accessor per parameter, so that every
##### parameter is reachable as `f(ps)` from the top-level parameter set. The
##### definitions are generated rather than written out because the field lists
##### are long and must not drift from the structs (or from the upstream
##### packages') definitions. To find where a parameter comes from, match its
##### name against the field lists of the structs above and the parameter
##### structs of Thermodynamics, SurfaceFluxes, and Insolation.
#####

# Forward TurbulenceConvection parameters: one accessor taking the top-level
# set, which delegates to one taking the turbconv set.
const TCPS = TurbulenceConvectionParameters
for var in fieldnames(TCPS)
    @eval $var(ps::ACAP) = $var(turbconv_params(ps))
end
for fn in fieldnames(TCPS)
    @eval $(fn)(ps::ATCP) = ps.$(fn)
end

# Forward the Thermodynamics parameters, so that e.g. `CAP.R_d(ps)` works.
for var in fieldnames(TD.Parameters.ThermodynamicsParameters)
    @eval $var(ps::ACAP) = TD.Parameters.$var(thermodynamics_params(ps))
end
# Thermodynamics derived parameters: functions of the fields above rather than
# fields themselves, so they must be listed explicitly.
for var in [:Rv_over_Rd, :kappa_d, :e_int_v0, :e_int_i0, :cv_v, :cv_l, :cv_d]
    @eval $var(ps::ACAP) = TD.Parameters.$var(thermodynamics_params(ps))
end

