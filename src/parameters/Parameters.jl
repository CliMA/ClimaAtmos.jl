  - `T_equator_wet`: Equatorial temperature of the moist Held-Suarez benchmark
    [K].
  - `T_min_hs`: Minimum temperature of the Held-Suarez relaxation profile [K].
  - `Δθ_z`: Vertical gradient of potential temperature in the Held-Suarez
    relaxation profile [K/m].
  - `alpha_rayleigh_w`: Rayleigh damping coefficient for vertical velocity [1/s].
  - `alpha_rayleigh_uh`: Rayleigh damping coefficient for horizontal velocity
    [1/s].
  - `alpha_rayleigh_tracer`: Rayleigh damping coefficient for tracers [1/s].
  - `zd_viscous`: Height at which viscous sponge damping begins [m].
  - `zd_rayleigh`: Height at which Rayleigh sponge damping begins [m].
  - `kappa_2_sponge`: Viscous sponge coefficient `κ₂` [m²/s].
  - `idealized_ocean_albedo`: Ocean surface albedo for idealized simulations [-].
  - `water_refractive_index`: Refractive index of water relative to air, for the
