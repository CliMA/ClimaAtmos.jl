"""
    NonOrographicGravityWaveParameters{FT} <: AbstractGravityWaveParameters

Parameters of the Alexander-Dunkerton non-orographic gravity-wave
parameterization.

The source spectrum is a Gaussian in phase speed, launched at a fixed pressure
level, with a total momentum flux that varies with latitude. Loaded only when
the scheme is enabled.

# Fields

  - `source_pressure`: Pressure of the wave source level [Pa].
  - `damp_pressure`: Pressure above which the remaining flux is deposited [Pa].
  - `source_height`: Height of the wave source level [m].
  - `Bw`: Spectral amplitude of the broad (westward) wave component [m²/s²].
  - `Bn`: Spectral amplitude of the narrow wave component [m²/s²].
  - `dc`: Phase-speed resolution of the spectral grid [m/s].
  - `cmax`: Maximum phase speed of the spectral grid [m/s].
  - `c0`: Reference phase speed [m/s].
  - `nk`: Number of wave bands [-].
  - `cw`: Phase-speed half-width of the broad component [m/s].
  - `cw_tropics`: Phase-speed half-width of the broad component in the tropics
    [m/s].
  - `cn`: Phase-speed half-width of the narrow component [m/s].
  - `Bt_0`: Background total source momentum flux [Pa].
  - `Bt_n`: Amplitude of the Northern Hemisphere flux enhancement [Pa].
  - `Bt_s`: Amplitude of the Southern Hemisphere flux enhancement [Pa].
  - `Bt_eq`: Amplitude of the equatorial flux enhancement [Pa].
  - `ϕ0_n`: Center latitude of the Northern Hemisphere enhancement [degrees].
  - `ϕ0_s`: Center latitude of the Southern Hemisphere enhancement [degrees].
  - `dϕ_n`: Latitudinal width of the Northern Hemisphere enhancement [degrees].
  - `dϕ_s`: Latitudinal width of the Southern Hemisphere enhancement [degrees].

