"""
    OrographicGravityWaveParameters{FT} <: AbstractGravityWaveParameters

Parameters of the Garner (2005) orographic gravity-wave drag parameterization.

Subgrid orography in a grid cell is described by a distribution of mountains of
height `h`, whose width scales as `L ∝ h^γ` and whose number density scales as
`n(h) ∝ h^(-ϵ)`. Waves above the critical height `h_crit` propagate and are
handled by the linear drag; the blocked flow below it is handled by the
nonlinear drag. Loaded only when the scheme is enabled.

# Fields

  - `γ`: Mountain height-width exponent in `L ∝ h^γ` [-].
  - `ϵ`: Number-density exponent in `n(h) ∝ h^(-ϵ)` [-].
  - `β`: Mountain shape exponent in `L(z) = L_b (1 - z/h)^β`; 1 is triangular,
    below 1 blunt, above 1 pointy [-].
  - `h_frac`: Height fraction in the blocking threshold `h_crit = h_frac V / N`
    [-].
  - `ρscale`: Density scale factor [-].
  - `L0`: Reference horizontal mountain width [m].
  - `a0`: Coefficient of the propagating (linear) wave drag [-].
  - `a1`: Coefficient of the nonpropagating (blocked) drag [-].
  - `Fr_crit`: Critical Froude number, the nondimensional critical height [-].
"""
Base.@kwdef struct OrographicGravityWaveParameters{FT} <: AGWP
    γ::FT                    # mountain_height_width_exponent: L ∝ h^γ (equation 14, paper suggests γ ≈ 0.4)
    ϵ::FT                    # number_density_exponent: number density of orography in a grid cell, n(h) ∝ h^(-ε)
    β::FT                    # mountain_shape_parameter: L(z) = L_b(1 - z/h)^β (equation 12), β=1 for triangular mountains and β<1 for blunt mountains, β>1 for pointy mountains
    h_frac::FT               # critical_height_threshold: h_crit = h_frac * (V / N), height fraction for blocking threshold
    ρscale::FT               # density_scale_factor: density scale factor for dimensional analysis
    L0::FT                   # reference_mountain_width: L_0 = 80 km, reference horizontal scale
    a0::FT                   # linear_drag_coefficient: a_0 = 0.9, coefficient for propagating wave drag
    a1::FT                   # nonlinear_drag_coefficient: a_1 = 3.0, coefficient for nonpropagating (blocked) drag
    Fr_crit::FT              # critical_froude_number: Fr_crit = 0.7, critical Froude number h̃_c = Fr_crit
end

# Physical/tuning parameters for the Beres (2004) convective gravity-wave source.
"""
    BeresSourceParameters{FT} <: AbstractGravityWaveParameters

Parameters of the Beres (2004) convective source for the non-orographic
gravity-wave scheme.

The source spectrum is obtained by integrating the convective heating spectrum
over frequency, with the heating depth and horizontal cell width setting the
vertical and horizontal wavenumbers. Loaded only when the Beres source is
enabled.

# Fields

  - `Q0_threshold`: Minimum convective heating rate that activates the source
    [K/s].
  - `scale_factor`: Dimensionless amplitude scaling; folds the `ρ₀/(L τ)`
    prefactor, the `|Q_t|²` weight, and empirical tuning into one number [-].
  - `σ_x`: Horizontal half-width of a convective cell [m].
  - `ν_min`: Minimum angular frequency of the frequency integration [rad/s].
  - `ν_max`: Maximum angular frequency of the frequency integration [rad/s].
  - `n_ν`: Number of quadrature points in frequency; must be `4k + 1` for the
    composite Boole's rule [-].
  - `h_heat_min`: Minimum heating depth that activates the source, filtering out
    shallow convection [m].
  - `n_h_avg`: Number of heating depths to average the spectrum over; 1 disables
    averaging and 3 or more smooths the resonance peak [-].
  - `Δh_frac`: Fractional half-range of the heating-depth average, `h ± Δh_frac h`;
    used only when `n_h_avg > 1` [-].
  - `z_bot_floor`: Lowest allowed bottom of the convective heating envelope,
    excluding the boundary-layer turbulence signal [m].
  - `steady_dc_frac`: Weight of the steady DC heating, `Q_t(0)² = steady_dc_frac ν_min`, setting the steady-to-transient amplitude ratio [-].
  - `L_system`: Largest convective-system scale, setting `k_min = 2π / L_system`
    for the steady source [m].
"""
Base.@kwdef struct BeresSourceParameters{FT} <: AGWP
    Q0_threshold::FT         # K/s, minimum heating rate to activate Beres
    scale_factor::FT         # dimensionless amplitude scaling (folds ρ₀/(Lτ), |Q_t|² weight, tuning)
    σ_x::FT                  # m, convective cell horizontal half-width
    ν_min::FT                # 1/s, min frequency (period ~120 min)
    ν_max::FT                # 1/s, max frequency (period ~10 min)
    n_ν::Int                 # quadrature points (must be 4k+1: 5, 9, 13...)
    h_heat_min::FT           # m, minimum heating depth to activate (filters shallow convection)
    n_h_avg::Int             # number of h values to average over (1 = no averaging)
    Δh_frac::FT              # fractional half-range for h averaging: h ± Δh_frac·h
    z_bot_floor::FT          # m, minimum allowed z_bot (excludes PBL turbulence in Q_conv)
    steady_dc_frac::FT       # steady DC heating weight: Q_t(0)² = steady_dc_frac·ν_min
    L_system::FT             # m, largest convective-system scale; sets k_min=2π/L for the steady source
end

"""
    ClimaAtmosParameters{FT, ...} <: AbstractClimaAtmosParameters

Top-level parameter set of a ClimaAtmos simulation.

